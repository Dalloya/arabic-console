/* ---- engine lookups (tables only; the rules live in the functions below) - */
static const struct ArabicLetter *find_letter(unsigned int cp) {
    size_t i;
    for (i = 0; i < ARABIC_LETTER_COUNT; ++i)
        if (arabic_letters[i].base == cp) return &arabic_letters[i];
    return NULL;
}

static int transparent_cp(unsigned int cp) {
    size_t lo = 0, hi = TRANSPARENT_CODEPOINT_COUNT;
    while (lo < hi) {
        size_t mid = (lo + hi) / 2;
        if (transparent_codepoints[mid] < cp) lo = mid + 1;
        else hi = mid;
    }
    return lo < TRANSPARENT_CODEPOINT_COUNT && transparent_codepoints[lo] == cp;
}

static char joining_of(unsigned int cp) {
    size_t i;
    for (i = 0; i < ARABIC_JOINING_COUNT; ++i)
        if (arabic_joining[i].base == cp) return arabic_joining[i].joining;
    if (transparent_cp(cp)) return 'T';
    return 'U';
}

static int lam_alef_variant(unsigned int cp, unsigned int *isol, unsigned int *fina) {
    size_t i;
    for (i = 0; i < LAM_ALEF_COUNT; ++i)
        if (lam_alef_table[i].alef == cp) {
            if (isol) *isol = lam_alef_table[i].isol;
            if (fina) *fina = lam_alef_table[i].fina;
            return 1;
        }
    return 0;
}

static unsigned int draw_codepoint(unsigned int cp, int connector) {
    size_t i;
    for (i = 0; i < DEDICATED_MARK_CELL_COUNT; ++i)
        if (dedicated_mark_cells[i].logical == cp)
            return connector ? dedicated_mark_cells[i].connector
                             : dedicated_mark_cells[i].terminal;
    return cp;
}

static int shadda_combo_vowel(unsigned int cp) {
    size_t i;
    for (i = 0; i < 6; ++i) if (shadda_combo_vowels[i] == cp) return 1;
    return 0;
}

static unsigned int shadda_combo_codepoint(unsigned int vowel, int connector) {
    size_t i;
    for (i = 0; i < 6; ++i)
        if (shadda_combo_vowels[i] == vowel)
            return (connector ? shadda_combo_conn : shadda_combo_plain)[i];
    return vowel;
}

/* A transparent mark receives a connector only if the preceding logical
 * letter has a forward join (its shaped form is initial or medial) — the
 * same rule ar_type.c's mark_after_forward_join applies, including the
 * lam-alef exception: a mark between a lam and its ligated alef takes the
 * plain cell, not the connector. */
static int mark_after_forward_join(const unsigned int *w, size_t n, size_t idx) {
    size_t prior = idx, j;
    const struct ArabicLetter *cur, *next;
    unsigned int nxt = 0;
    while (prior > 0) {
        --prior;
        if (!transparent_cp(w[prior])) break;
    }
    if (prior == idx || !find_letter(w[prior])) return 0;
    cur = find_letter(w[prior]);
    for (j = prior + 1; j < n; ++j)
        if (!transparent_cp(w[j])) { nxt = w[j]; break; }
    if (w[prior] == 0x0644 && lam_alef_variant(nxt, NULL, NULL)) return 0;
    next = find_letter(nxt);
    return next && next->form[3].unicode && cur->form[1].unicode;
}

/* Shape one Arabic word (a segment holds no spaces) into cells in LOGICAL
 * order; the caller reverses the cells for the visual line.  Letters take
 * their positional form exactly as tools/join.py chooses it; a lam + alef
 * pair becomes the one ligature cell; marks become U+E0xx cells. */
static size_t shape_word(const unsigned int *w, size_t n, unsigned int *out) {
    size_t i, m = 0;
    for (i = 0; i < n; ++i) {
        unsigned int cp = w[i], prev = 0, nxt = 0, isol = 0, fina = 0;
        const struct ArabicLetter *cur;
        size_t j;
        int jp, jn;
        if (cp == 0x0640) { out[m++] = cp; continue; } /* tatweel: a cell, no form */
        if (transparent_cp(cp)) {
      /* a vowel whose cell belongs to the shadda right before
             * it has no cell of its own; the shadda emitted the pair. */
            if (shadda_combo_vowel(cp) && i > 0 && w[i - 1] == 0x0651) continue;
            if (cp == 0x0651 && i + 1 < n && shadda_combo_vowel(w[i + 1])) {
                out[m++] = shadda_combo_codepoint(w[i + 1],
                                                  mark_after_forward_join(w, n, i));
                ++i; /* the vowel is covered by this one stacked cell */
                continue;
            }
            out[m++] = draw_codepoint(cp, mark_after_forward_join(w, n, i));
            continue;
        }
        cur = find_letter(cp);
        if (!cur) { out[m++] = cp; continue; }
        for (j = i; j > 0 && transparent_cp(w[j - 1]); --j) {}
        if (j > 0) prev = w[j - 1];
        for (j = i + 1; j < n && transparent_cp(w[j]); ++j) {}
        if (j < n) nxt = w[j];
    /* this alef belongs to the lam before it; the lam's cell
         * carries the pair, so the alef emits nothing. */
        if (lam_alef_variant(cp, NULL, NULL) && prev == 0x0644) continue;
        if (cp == 0x0644 && lam_alef_variant(nxt, &isol, &fina)) {
            jp = prev && (joining_of(prev) == 'D' || joining_of(prev) == 'C');
            out[m++] = jp ? fina : isol;
            continue;
        }
        jp = cur->form[3].unicode && prev && (joining_of(prev) == 'D' || joining_of(prev) == 'C');
        jn = cur->form[1].unicode && ((find_letter(nxt) && find_letter(nxt)->form[3].unicode) || joining_of(nxt) == 'C');
        /* medi/fina/init/isol, the join.py positions in that order. */
        out[m++] = cur->form[jp ? (jn ? 2 : 3) : (jn ? 1 : 0)].unicode ?: cp;
    }
    return m;
}

/* ---- byte output --------------------------------------------------------- */
static int out_fd = 1;
static int ar_out_fd = -1;      /* ARSH_OUT_FD: the child keeps its stdout */
static int ar_stdin_own = 0;    /* ARSH_STDIN=own: the child keeps its stdin */
static int ar_stderr_own = 0;   /* ARSH_STDERR=own: the child keeps its stderr */
static unsigned char *outbuf;
static size_t outlen, outcap;
static int out_onlcr;
static struct termios saved_stdin;
static int stdin_was_tty;

static int flush_out(void) {
    size_t done = 0;
    while (done < outlen) {
        ssize_t r = write(out_fd, outbuf + done, outlen - done);
        if (r <= 0) { outlen = 0; return -1; }
        done += (size_t)r;
    }
    outlen = 0;
    return 0;
}

/* ---- the row hold buffer --------------------
 * A row the console draws itself is anchored at the RIGHT margin, so the
 * row's WIDTH must be known before its first cell is written.  The shaped
 * line is therefore emitted into this hold buffer first, measured in columns,
 * and only then written out behind its pad.  Passthrough rows (no Arabic, or
 * producer-shaped forms) never enter the hold buffer: they are the producer's
 * own bytes, not a row the console drew. */
static unsigned char *holdbuf;
static size_t holdlen, holdcap;
static int hold_on;

static int out_bytes(const unsigned char *s, size_t n) {
    if (hold_on) {
        if (holdlen + n > holdcap) {
            size_t ncap = holdcap ? holdcap * 2 : 4096;
            unsigned char *grown;
            while (ncap < holdlen + n) ncap *= 2;
            grown = realloc(holdbuf, ncap);
            if (!grown) return -1;
            holdbuf = grown;
            holdcap = ncap;
        }
        memcpy(holdbuf + holdlen, s, n);
        holdlen += n;
        return 0;
    }
    if (outlen + n > outcap) {
        if (flush_out()) return -1;
        if (n > outcap) {
            unsigned char *grown = realloc(outbuf, outlen + n);
            if (!grown) return -1;
            outbuf = grown;
            outcap = outlen + n;
        }
    }
    memcpy(outbuf + outlen, s, n);
    outlen += n;
    return 0;
}

static int out_byte(unsigned char b) { return out_bytes(&b, 1); }

static int out_utf8(unsigned int cp) {
    unsigned char b[4];
    size_t n;
    if (cp <= 0x7f) { b[0] = (unsigned char)cp; n = 1; }
    else if (cp <= 0x7ff) { b[0] = 0xc0 | (cp >> 6); b[1] = 0x80 | (cp & 63); n = 2; }
    else if (cp <= 0xffff) { b[0] = 0xe0 | (cp >> 12); b[1] = 0x80 | ((cp >> 6) & 63); b[2] = 0x80 | (cp & 63); n = 3; }
    else { b[0] = 0xf0 | (cp >> 18); b[1] = 0x80 | ((cp >> 12) & 63); b[2] = 0x80 | ((cp >> 6) & 63); b[3] = 0x80 | (cp & 63); n = 4; }
    return out_bytes(b, n);
}

/* ---- the row anchor -------------------------
 * A row the console draws is anchored at the RIGHT margin, the way the banner
 * and the live line are.  The anchor is THIS ONE SWITCH: the number of blank
 * cells written before the row's first cell.  `return 0;` restores the old
 * left margin and nothing else moves: the shaper, the lexicon and the message
 * texts are untouched.  A row at least as wide as the terminal gets no pad -
 * the tty's own wrap continues it on the next line, exactly as before. */
static size_t console_width(void) {
    static size_t w;
    if (!w) {
        struct winsize ws;
        if (ioctl(out_fd, TIOCGWINSZ, &ws) == 0 && ws.ws_col)
            w = ws.ws_col;
        else
            w = 80;    /* the console's designed width */
    }
    return w;
}

/* Columns a UTF-8 byte run occupies on the console: one per codepoint (the
 * console font is single-width throughout). */
static size_t utf8_columns(const unsigned char *s, size_t n) {
    size_t i, cols = 0;
    for (i = 0; i < n; ++i)
        if ((s[i] & 0xc0) != 0x80) ++cols;
    return cols;
}

/* The anchor applies on the console.  The same predicate the editor uses
 * (ar_type.c's is_vt_console): KDGKBTYPE answers only on a VT console, so a
 * pty, a pipe or a redirect is not the console and its byte stream is left
 * exactly as the producer wrote it (a redirect must not gain pad spaces).
 * This decides WHERE the console display is; msg_right_pad() stays the one
 * switch for the anchor itself. */
static int out_is_console(void) {
    static int known, yes;
    int kb = 0;
    if (!known) { yes = ioctl(out_fd, KDGKBTYPE, &kb) >= 0; known = 1; }
    return yes;
}

static size_t msg_right_pad(size_t cols) {
    size_t w = console_width();
    if (!out_is_console()) return 0;
    return cols < w ? w - cols : 0;
}

/* ---- line processing ----------------------------------------------------- */
#define MAX_LINE_CP 8192
static unsigned int line_cp[MAX_LINE_CP];
static size_t line_byte_off[MAX_LINE_CP + 1];
static unsigned int word_cells[MAX_LINE_CP];
/* Explicit field mode.  Zero keeps the shipped natural-width renderer. */
static size_t justify_width;

static int form_joins_forward(unsigned int cp) {
    size_t i;
    for (i = 0; i < ARABIC_LETTER_COUNT; ++i)
        if (cp == arabic_letters[i].form[1].unicode || cp == arabic_letters[i].form[2].unicode)
            return 1;
    return 0;
}

static int form_joins_backward(unsigned int cp) {
    size_t i;
    if (cp == 0xFEF6 || cp == 0xFEF8 || cp == 0xFEFA || cp == 0xFEFC)
        return 1; /* final lam-alef ligatures */
    for (i = 0; i < ARABIC_LETTER_COUNT; ++i)
        if (cp == arabic_letters[i].form[2].unicode || cp == arabic_letters[i].form[3].unicode)
            return 1;
    return 0;
}

/* word_cells are logical L-to-R here; the caller reverses them for display.
 * Sakhr inserts at the last legal join, nearest the visual left edge. */
static size_t justify_word_cells(size_t n) {
    size_t i, extra;
    if (!n || !justify_width || n >= justify_width || justify_width > MAX_LINE_CP)
        return n;
    extra = justify_width - n;
    for (i = n - 1; i > 0; --i) {
        if (!form_joins_forward(word_cells[i - 1]) ||
            !form_joins_backward(word_cells[i])) continue;
        memmove(word_cells + i + extra, word_cells + i,
                (n - i) * sizeof(word_cells[0]));
        while (extra--) word_cells[i + extra] = 0x0640;
        return justify_width;
    }
    return n; /* no genuine connection to stretch */
}

/* Strict UTF-8 decode of p[0..n).  Returns the codepoint count and fills
 * line_cp plus the per-codepoint byte offsets, or -1 on any invalid byte. */
static ssize_t decode_line(const unsigned char *p, size_t n) {
    size_t i = 0, m = 0;
    while (i < n) {
        unsigned int cp;
        size_t len, k;
        unsigned char c = p[i];
        if (c < 0x80) { cp = c; len = 1; }
        else if ((c & 0xe0) == 0xc0) { cp = c & 0x1f; len = 2; }
        else if ((c & 0xf0) == 0xe0) { cp = c & 0x0f; len = 3; }
        else if ((c & 0xf8) == 0xf0) { cp = c & 0x07; len = 4; }
        else return -1;
        if (i + len > n) return -1;
        for (k = 1; k < len; ++k) {
            if ((p[i + k] & 0xc0) != 0x80) return -1;
            cp = (cp << 6) | (p[i + k] & 0x3f);
        }
        if ((len == 2 && cp < 0x80) || (len == 3 && cp < 0x800) ||
            (len == 4 && cp < 0x10000) || cp > 0x10FFFF ||
            (cp >= 0xD800 && cp <= 0xDFFF)) return -1;
        if (m >= MAX_LINE_CP) return -1;
        line_cp[m] = cp;
        line_byte_off[m++] = i;
        i += len;
    }
    line_byte_off[m] = n;
    return (ssize_t)m;
}

/* 0 = OTHER, 1 = SPACE, 2 = ARABIC. */
static int class_of(unsigned int cp) {
    if (cp == 0x20) return 1;
    if (cp == 0x0640 || find_letter(cp) || transparent_cp(cp)) return 2;
    return 0;
}

static int is_forms(unsigned int cp) { return cp >= 0xFE70 && cp <= 0xFEFC; }

/* ---- Route B — the wrapper's own closed table ------------ */
/* This is the FLOOR of the message layer (D2 Route B).  Arabic-first routes
 * A1 (the locale + the packages' own catalogues) and A3 (a bash catalogue we
 * author) answer the same messages upstream; this table covers what reaches
 * us English anyway: a host with no catalogue, the pass-through guarantee,
 * and the owner's ARSH_MESSAGES=off switch.  English keys are matched
 * EXACTLY and only when the line ends in ": <MSG>"; an unmatched line passes
 * through byte-for-byte, never swallowed (the layer-3 contract,
 * tools/terjaman.c:28-45, states the same rule for the toolchain).  The
 * table lives here and nowhere else.
 *
 *   command not found           -> الأمر غير موجود   (A3 if bash consults
 *                                   our catalogue; else this entry)
 *   No such file or directory   -> لا يوجد ملف أو دليل بهذا الاسم   (A1)
 *   Permission denied           -> الإذن مرفوض        (A1)
 *   Is a directory              -> إنه دليل            (A1, capital I)
 *   cannot execute binary file  -> لا يمكن تنفيذ ملف ثنائي   (A3 if possible)
 */
struct msg_entry { const char *en; const char *ar; };
static const struct msg_entry msg_table[] = {
    {"command not found",          "الأمر غير موجود"},
    {"No such file or directory",  "لا يوجد ملف أو دليل بهذا الاسم"},
    {"Permission denied",          "الإذن مرفوض"},
    {"Is a directory",             "إنه دليل"},
    {"cannot execute binary file", "لا يمكن تنفيذ ملف ثنائي"},
};
static const char *const BASH_PREFIX_AR = "السطر ";  /* + <N> + ": " */

static int ar_messages_on = 1;      /* ARSH_MESSAGES=off disables Route B */
static unsigned char trbuf[MAX_LINE_CP * 4 + 64];

/* Match a bash structural prefix at the start of p[0..n): an optional
 * leading path (a run of non-space non-colon bytes ending in '/', as in the
 * console's "/bin/bash"), then the literal "bash: line ", one or more
 * digits, then ": ".  Return the length of the matched prefix, or 0; the
 * byte length of the leading path portion (everything before "bash") is
 * reported through *path_len.  Only the literal program name "bash"
 * qualifies; another producer's "line N:" stays as it is. */
static size_t match_bash_prefix(const unsigned char *p, size_t n,
                                size_t *dig_off, size_t *dig_len,
                                size_t *path_len) {
    size_t i = 0, j = 0;
    static const char *const BASH = "bash: line ";
    size_t blen = strlen(BASH);
    /* The first token is the producer's argv[0]: bare "bash" or a path.
     * Match from after its last '/', so both forms qualify. */
    while (j < n && p[j] != ' ' && p[j] != ':') ++j;
    for (i = j; i > 0 && p[i - 1] != '/'; --i) ;
    if (i + blen > n || memcmp(p + i, BASH, blen)) return 0;
    i += blen;
    {
        size_t d = i;
        while (i < n && p[i] >= '0' && p[i] <= '9') ++i;
        if (i == d) return 0;
        if (i + 1 >= n || p[i] != ':' || p[i + 1] != ' ') return 0;
        if (dig_off) *dig_off = d;
        if (dig_len) *dig_len = i - d;
        if (path_len) *path_len = d - blen;   /* bytes before "bash" */
    }
    return i + 2;
}

/* Route B: translate the logical line p[0..n) into trbuf.  Returns the new
 * byte length, or 0 when nothing matched.  Runs before the placement rule,
 * on the logical line, in logical order. */
static size_t translate_line(const unsigned char *p, size_t n) {
    size_t d_off = 0, d_len = 0, path_len = 0, prefix_len;
    const struct msg_entry *body = NULL;
    size_t body_off = 0, tn = 0, i;

    prefix_len = match_bash_prefix(p, n, &d_off, &d_len, &path_len);
    for (i = 0; i < sizeof(msg_table) / sizeof(msg_table[0]); ++i) {
        size_t elen = strlen(msg_table[i].en);
        if (n >= elen + 2 && p[n - elen - 2] == ':' && p[n - elen - 1] == ' ' &&
            !memcmp(p + n - elen, msg_table[i].en, elen)) {
            body = &msg_table[i];
            body_off = n - elen;
            break;
        }
    }
    if (!prefix_len && !body) return 0;

    if (prefix_len) {
        size_t alen = strlen(BASH_PREFIX_AR);
        size_t rest_start = prefix_len, rest_end = body ? body_off : n;
        /* SPEC D3: a path is a path — a path-qualified argv[0] is printed
         * exactly as given ("/bin/bash: السطر ..."), so its Latin letters
         * stay by right.  The bare form keeps the pre-72 behaviour (no
         * "bash" token in the translation). */
        if (path_len > 0) {
            memcpy(trbuf + tn, p, path_len + 4); tn += path_len + 4;
            trbuf[tn++] = ':'; trbuf[tn++] = ' ';
        }
        memcpy(trbuf + tn, BASH_PREFIX_AR, alen); tn += alen;
        memcpy(trbuf + tn, p + d_off, d_len); tn += d_len;
        trbuf[tn++] = ':'; trbuf[tn++] = ' ';
        if (rest_end > rest_start) {
            memcpy(trbuf + tn, p + rest_start, rest_end - rest_start);
            tn += rest_end - rest_start;
        }
    } else {
        memcpy(trbuf + tn, p, body_off); tn += body_off;
    }
    if (body) {
        size_t alen = strlen(body->ar);
        memcpy(trbuf + tn, body->ar, alen); tn += alen;
    }
    return tn;
}

/* D1 Step 1: the line's base direction.  Skip a producer prefix — a token of
 * [A-Za-z0-9._/+-] followed by ": " — then take the first strong codepoint:
 * an Arabic letter (U+0621-U+064A, not a mark, not tatweel) -> RTL, an ASCII
 * letter -> LTR, neither -> RTL (the console default).  This one function is
 * the owner's switch. */
static int line_base_is_rtl(const unsigned int *cp, size_t m) {
    size_t i = 0, j = 0;
    while (j < m) {
        unsigned int c = cp[j];
        if (!((c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') ||
              (c >= '0' && c <= '9') || c == '.' || c == '_' ||
              c == '/' || c == '+' || c == '-')) break;
        ++j;
    }
    if (j > 0 && j + 1 < m && cp[j] == ':' && cp[j + 1] == ' ') i = j + 2;
    for (; i < m; ++i) {
        unsigned int c = cp[i];
        if (c >= 0x0621 && c <= 0x064A) return 1;
        if ((c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z')) return 0;
    }
    return 1;
}

/* D1 Step 2: cut the logical line into units, left to right.  kind 0 = byte
 * unit (island, plain segment, space), kind 1 = Arabic chunk, kind 2 = an
 * atomic quoted span or bare Arabic path. */
static struct { unsigned char kind; size_t start, end; } units[MAX_LINE_CP];
static size_t nunits;

/* A maximal non-space token that carries BOTH a slash and Arabic is ONE
 * island, and its boundary is the token edge, never a slash.  TRUE only when
 * `i` is the token's FIRST codepoint (the one place the token may be cut), so
 * the plain-segment scan below stops at the token start and the loop's own
 * top check cuts the whole token there.  Stopping at an interior slash — the
 * pre-89 behaviour — left the token's prefix behind as its own unit, and the
 * RTL unit reversal then painted it after the island: the تاريخ row's
 * `03/10/2026م` reached the screen as `/10/2026` م `03` (reproduced
 * with the tool's own line; minimal repro `المسار: 03/مشاريع`). */
static int bare_path_token(const unsigned int *cp, size_t i, size_t m) {
    size_t e = i, k;
    int has_slash = 0, has_arabic = 0;
    if (i >= m || (i > 0 && cp[i - 1] != ' ')) return 0;
    while (e < m && cp[e] != ' ' && cp[e] != '\'' && cp[e] != '"') ++e;
    for (k = i; k < e; ++k) {
        if (cp[k] == '/') has_slash = 1;
        if (class_of(cp[k]) == 2) has_arabic = 1;
    }
    return has_slash && has_arabic;
}

static size_t cut_units(const unsigned int *cp, size_t m) {
    size_t i = 0, u = 0;
    while (i < m) {
        /* Quotes define an atomic boundary, including spaces and every slash
         * inside the span.  The input grammar has no escaped quote form. */
        if (cp[i] == '\'' || cp[i] == '"') {
            unsigned int quote = cp[i];
            size_t s = i++;
            while (i < m && cp[i] != quote) ++i;
            if (i < m) ++i;
            units[u].kind = 2; units[u].start = s; units[u].end = i; ++u;
            continue;
        }
        /* A bare path is one maximal non-space token when it has both a slash
         * and Arabic.  Its boundary is the token edge, never a slash. */
        if (cp[i] != ' ') {
            size_t e = i, k;
            int has_slash = 0, has_arabic = 0;
            while (e < m && cp[e] != ' ' && cp[e] != '\'' && cp[e] != '"') ++e;
            for (k = i; k < e; ++k) {
                if (cp[k] == '/') has_slash = 1;
                if (class_of(cp[k]) == 2) has_arabic = 1;
            }
            if (has_slash && has_arabic) {
                units[u].kind = 2; units[u].start = i; units[u].end = e; ++u;
                i = e;
                continue;
            }
        }
        if (class_of(cp[i]) == 2) {
            /* Arabic chunk: Arabic codepoints plus a space run that is
             * immediately followed by Arabic, so a phrase stays one unit. */
            size_t s = i++;
            while (i < m) {
                if (class_of(cp[i]) == 2) { ++i; continue; }
                if (cp[i] == ' ') {
                    size_t j = i;
                    while (j < m && cp[j] == ' ') ++j;
                    if (j < m && class_of(cp[j]) == 2) { i = j; continue; }
                }
                break;
            }
            units[u].kind = 1; units[u].start = s; units[u].end = i; ++u;
        } else {
            /* Non-Arabic: S = the maximal stretch with no Arabic codepoint,
       * stopped at a bare-path token's own edge (the slash inside
             * such a token is never a unit boundary). */
            size_t s = i;
            while (i < m && class_of(cp[i]) != 2 &&
                   cp[i] != '\'' && cp[i] != '"' &&
                   !bare_path_token(cp, i, m)) ++i;
            {
                size_t e = i, ls = s, le = e, k;
                int has_ascii = 0;
                while (ls < e && cp[ls] == ' ') ++ls;
                while (le > ls && cp[le - 1] == ' ') --le;
                for (k = ls; k < le; ++k)
                    if ((cp[k] >= 'A' && cp[k] <= 'Z') ||
                        (cp[k] >= 'a' && cp[k] <= 'z')) { has_ascii = 1; break; }
                if (has_ascii) {
                    /* letter island: leading space, C whole, trailing space */
                    if (ls > s) { units[u].kind = 0; units[u].start = s; units[u].end = ls; ++u; }
                    units[u].kind = 0; units[u].start = ls; units[u].end = le; ++u;
                    if (le < e) { units[u].kind = 0; units[u].start = le; units[u].end = e; ++u; }
                } else {
                    /* plain: maximal same-class runs, a space run its own
                     * segment — exactly the pre-66 layout. */
                    size_t j = s;
                    while (j < e) {
                        int cls = class_of(cp[j]);
                        size_t jj = j + 1;
                        while (jj < e && class_of(cp[jj]) == cls) ++jj;
                        units[u].kind = 0; units[u].start = j; units[u].end = jj; ++u;
                        j = jj;
                    }
                }
            }
        }
    }
    return u;
}

/* D1 Step 3: emit one unit.  Arabic chunks are shaped and their cells
 * reversed (an Arabic word reads RTL either way); byte units are emitted
 * byte-for-byte. */
static int emit_unit(size_t ui, const unsigned char *q) {
    if (units[ui].kind == 1) {
        size_t cells = shape_word(line_cp + units[ui].start,
                                  units[ui].end - units[ui].start, word_cells);
        size_t k;
        cells = justify_word_cells(cells);
        for (k = cells; k > 0; --k)
            if (out_utf8(word_cells[k - 1])) return -1;
    } else if (units[ui].kind == 2) {
        size_t i = units[ui].start;
        while (i < units[ui].end) {
            size_t j;
            if (class_of(line_cp[i]) == 2) {
                size_t cells;
                size_t k;
                j = i + 1;
                while (j < units[ui].end && class_of(line_cp[j]) == 2) ++j;
                cells = shape_word(line_cp + i, j - i, word_cells);
                for (k = cells; k > 0; --k)
                    if (out_utf8(word_cells[k - 1])) return -1;
            } else {
                j = i + 1;
                while (j < units[ui].end && class_of(line_cp[j]) != 2) ++j;
                if (out_bytes(q + line_byte_off[i],
                              line_byte_off[j] - line_byte_off[i])) return -1;
            }
            i = j;
        }
    } else {
        if (out_bytes(q + line_byte_off[units[ui].start],
                      line_byte_off[units[ui].end] -
                          line_byte_off[units[ui].start])) return -1;
    }
    return 0;
}

/* Process the content of one line (its terminator is removed by the caller
 * and re-added after).  Returns 0, or -1 on a write error. */
static int process_line(const unsigned char *p, size_t n) {
    const unsigned char *q = p;
    size_t qn = n;
    ssize_t m = decode_line(p, n);
    size_t i;
    int has_arabic = 0, has_forms = 0;

    if (m < 0) { out_bytes(p, n); return flush_out(); }

    /* D2 Route B: translate the LOGICAL line before the placement rule (and
     * before the direction is decided), so a translated message turns Arabic
     * and is then rendered as Arabic.  A pipe in front of a filter is
     * forbidden here — it would cost the child its tty. */
    if (ar_messages_on) {
        size_t tn = translate_line(p, n);
        if (tn) { q = trbuf; qn = tn; }
    }

    m = decode_line(q, qn);
    if (m < 0) { out_bytes(q, qn); return flush_out(); }
    for (i = 0; i < (size_t)m; ++i) {
        if (class_of(line_cp[i]) == 2) has_arabic = 1;
        else if (is_forms(line_cp[i])) has_forms = 1;
    }
    /* No Arabic at all: byte-for-byte.  Presentation forms present: the
     * producer shaped this line itself — pass it through whole, never shape
     * it again and never reorder its intentional visual layout. */
    if (!has_arabic || has_forms) { out_bytes(q, qn); return flush_out(); }

    /* D1: cut into units, decide the base direction, emit — reversing the
     * unit sequence only when the base is RTL.
   * this is a row the console draws, so on the console it is
     * anchored at the RIGHT margin.  Emit it into the hold buffer first (the
     * pad has to be written before its first cell, so its width must be known
     * first), then write pad + row in one go. */
    nunits = cut_units(line_cp, (size_t)m);
    hold_on = 1;
    holdlen = 0;
    if (line_base_is_rtl(line_cp, (size_t)m)) {
        for (i = nunits; i > 0; --i)
            if (emit_unit(i - 1, q)) { hold_on = 0; return -1; }
    } else {
        for (i = 0; i < nunits; ++i)
            if (emit_unit(i, q)) { hold_on = 0; return -1; }
    }
    hold_on = 0;
    {
        size_t pad = msg_right_pad(utf8_columns(holdbuf, holdlen));
        for (i = 0; i < pad; ++i)
            if (out_byte(' ')) return -1;
        if (out_bytes(holdbuf, holdlen)) return -1;
    }
    return flush_out();
}

/* One chunk of the read stream.  terminated: it ended at '\n' (the '\n' is
 * not part of p).  The trailing '\r' of a CRLF pair is folded back into the
 * terminator, so reordering never moves it off the end of the line. */
static int emit_chunk(const unsigned char *p, size_t n, int terminated) {
    size_t content = n;
    int had_cr = 0;
    if (terminated && content && p[content - 1] == '\r') { --content; had_cr = 1; }
    if (process_line(p, content)) return -1;
    if (out_onlcr) {
        /* The tty below re-adds CRLF for a bare '\n'; emitting the '\r' too
         * would double it. */
        if (terminated && out_byte('\n')) return -1;
    } else {
        if (had_cr && out_byte('\r')) return -1;
        if (terminated && out_byte('\n')) return -1;
    }
    return flush_out();
}

/* ---- the pty driver ------------------------------------------------------ */
static volatile sig_atomic_t got_winch;
static volatile sig_atomic_t got_term;
static pid_t child_pid;

static void on_winch(int sig) { (void)sig; got_winch = 1; }
static void on_term(int sig) {
    (void)sig;
    got_term = 1;
  /* the child is a session leader, so its pid IS its process group -
     * term the GROUP, not the one process, or a descendant mid-pipeline
     * survives its parent's death.  A session leader always leads a group,
     * so the fallback is only for the impossible case. */
    if (child_pid > 0) {
        if (kill(-child_pid, SIGTERM) != 0) kill(child_pid, SIGTERM);
    }
}

/* the caller (ar-shell) cannot signal the program directly — it
 * lives in this wrapper's separate session behind a pty — so the console's
 * ^C arrives here as SIGINT.  Hand it to the child the way a terminal
 * would: write 0x03 into the pty master; the child pty's line discipline
 * then raises a real SIGINT in the child's foreground process group.  This
 * handler is async-signal-safe (write only, on a plain int set before the
 * loop reads anything).
 *
 * and ALSO signal the child's own group directly, because the pty route
 * only reaches the FOREGROUND group - a descendant that moved itself into
 * another group of that session would survive the terminal's ^C, which is not
 * what a console user means by interrupting.  kill() is async-signal-safe. */
static int master_for_signal = -1;
static void on_int(int sig) {
    (void)sig;
    if (master_for_signal >= 0) (void)!write(master_for_signal, "\003", 1);
    if (child_pid > 0) kill(-child_pid, SIGINT);
}

static void restore_stdin(void) {
    if (stdin_was_tty) tcsetattr(0, TCSANOW, &saved_stdin);
}

static void apply_winsize(int master) {
    struct winsize ws;
    if (ioctl(out_fd, TIOCGWINSZ, &ws) || !ws.ws_col || !ws.ws_row) {
        ws.ws_row = 25; ws.ws_col = 80; ws.ws_xpixel = 0; ws.ws_ypixel = 0;
    }
    ioctl(master, TIOCSWINSZ, &ws);
}

static void usage(void) {
    fprintf(stderr, "usage: شكل COMMAND [ARG...]   (arsh) — run COMMAND on a pty and\n"
                    "shape its Arabic output for the console.  Lines without Arabic,\n"
                    "escape sequences, and column layout outside Arabic runs are passed\n"
                    "through byte-for-byte; digit runs keep their internal order; lines\n"
                    "that already carry Presentation Forms are never shaped again.\n"
                    "AR_JUSTIFY_WIDTH=N explicitly pads Arabic words to N cells with tatweel.\n"
                    "ARSH_MESSAGES=off disables the wrapper's own message table (Route B).\n"
                    "ARSH_OUT_FD=n sends the shaped output to fd n (the console) while the\n"
                    "child keeps its own stdout; ARSH_STDIN=own / ARSH_STDERR=own leave the\n"
                    "child's stdin / stderr exactly as the caller set them\n"
                    "the shell's executor hosts one stream of a composed stage).\n");
}

#define LINEBUF_CAP (1 << 20)
static unsigned char linebuf[LINEBUF_CAP];
static size_t buflen;

/* Append stream bytes to the partial-line buffer, emit every complete line,
 * keep the tail.  Returns 0, or -1 on a write error. */
static int consume_stream(const unsigned char *p, size_t n) {
    size_t i, line_start = 0;
    for (i = 0; i < n; ++i) {
        if (p[i] == '\n') {
            if (buflen) {
                if (buflen + (i - line_start) > LINEBUF_CAP) {
                    /* a line longer than the buffer: emit what is buffered
                     * as a fragment and start over */
                    if (emit_chunk(linebuf, buflen, 0)) return -1;
                    buflen = 0;
                    if (i - line_start > LINEBUF_CAP) {
                        if (emit_chunk(p + line_start, i - line_start, 1)) return -1;
                        line_start = i + 1;
                        continue;
                    }
                }
                memcpy(linebuf + buflen, p + line_start, i - line_start);
                buflen += i - line_start;
                if (emit_chunk(linebuf, buflen, 1)) return -1;
                buflen = 0;
            } else {
                if (emit_chunk(p + line_start, i - line_start, 1)) return -1;
            }
            line_start = i + 1;
        }
    }
    if (line_start < n) {
        size_t keep = n - line_start;
        if (buflen + keep > LINEBUF_CAP) {
            if (emit_chunk(linebuf, buflen, 0)) return -1;
            buflen = 0;
        }
        memcpy(linebuf + buflen, p + line_start, keep);
        buflen += keep;
    }
    return 0;
}

static long now_ms(void) {
    struct timeval tv;
    gettimeofday(&tv, NULL);
    return (long)tv.tv_sec * 1000 + tv.tv_usec / 1000;
}

int main(int argc, char **argv) {
    int master, slave, status = 0, child_done = 0, stdin_eof = 0;
    long last_data;
    struct termios raw;
    struct sigaction sa;
    unsigned char buf[65536];
    pid_t pid;

    if (argc < 2) { usage(); return 2; }
    {
        const char *e = getenv("AR_JUSTIFY_WIDTH");
        if (e && *e) {
            char *end;
            unsigned long value;
            errno = 0; value = strtoul(e, &end, 10);
            if (errno || *end || !value || value > MAX_LINE_CP) {
                fprintf(stderr, "arsh: AR_JUSTIFY_WIDTH must be 1..%d\n", MAX_LINE_CP);
                return 2;
            }
            justify_width = (size_t)value;
        }
    }
    {
        const char *e = getenv("ARSH_MESSAGES");
        if (e && !strcmp(e, "off")) ar_messages_on = 0;
    }
  /* descriptor ownership for a HOSTED stage - one whose stdout or
     * stderr is terminal-bound while the shell's executor owns the others.
     * The defaults below are this wrapper's shipped behaviour exactly; each
     * switch only takes away the descriptor it names, so a caller that sets
     * none sees no change. */
    {
        const char *e = getenv("ARSH_OUT_FD");
        if (e && *e) {
            int n = atoi(e);
            if (n > 2) { out_fd = n; ar_out_fd = n; }
        }
        e = getenv("ARSH_STDIN");
        if (e && !strcmp(e, "own")) ar_stdin_own = 1;
        e = getenv("ARSH_STDERR");
        if (e && !strcmp(e, "own")) ar_stderr_own = 1;
    }
    if (openpty(&master, &slave, NULL, NULL, NULL)) {
        fprintf(stderr, "شكل: openpty: %s\n", strerror(errno));
        return 1;
    }
    if (isatty(out_fd)) {
        struct termios t;
    /* the tty below re-adds the CR only when it
         * PROCESSES output, so the CR may be dropped only with OPOST as well
         * as ONLCR; with OPOST off a bare LF would leave the next row at the
         * current column (measured: OPOST-on gave CRLF, OPOST-off bare LF). */
        if (!tcgetattr(out_fd, &t)) out_onlcr = (t.c_oflag & OPOST) && (t.c_oflag & ONLCR);
    }
    apply_winsize(master);
  master_for_signal = master;  /* ^C handoff target (see on_int) */
    if (!ar_stdin_own && isatty(0) && !tcgetattr(0, &saved_stdin)) {
        stdin_was_tty = 1;
        raw = saved_stdin;
        raw.c_lflag &= ~(ICANON | ISIG | ECHO);
        raw.c_iflag &= ~(ICRNL | IXON | ISTRIP | BRKINT);
        raw.c_cc[VMIN] = 1;
        raw.c_cc[VTIME] = 0;
        tcsetattr(0, TCSANOW, &raw);
    }
  /* the wrapper is a presentation layer, not a stage. When its shaped
     * reader disappears (the console feed closes, a redirection target fills
     * and goes away) the write fails and the error is handled as an error -
     * the wrapper must not die of SIGPIPE with the CHILD's status still
     * unreported.  The child restores the default below: a program run through
     * this wrapper keeps the signal semantics it would have had anywhere. */
    signal(SIGPIPE, SIG_IGN);
    memset(&sa, 0, sizeof(sa));
    sa.sa_handler = on_winch; sigaction(SIGWINCH, &sa, NULL);
    sa.sa_handler = on_term;
    sigaction(SIGTERM, &sa, NULL); sigaction(SIGHUP, &sa, NULL);
    signal(SIGINT, on_int); signal(SIGQUIT, SIG_IGN);
    signal(SIGCHLD, SIG_DFL);

    pid = fork();
    if (pid < 0) {
        fprintf(stderr, "شكل: fork: %s\n", strerror(errno));
        restore_stdin();
        return 1;
    }
    if (pid == 0) {
        /* exec keeps ignored signals ignored, so restore the defaults the
         * child needs for its own pty discipline (^C etc.). */
        signal(SIGINT, SIG_DFL); signal(SIGQUIT, SIG_DFL);
        signal(SIGTERM, SIG_DFL); signal(SIGHUP, SIG_DFL);
        signal(SIGWINCH, SIG_DFL); signal(SIGPIPE, SIG_DFL);
        setsid();
        ioctl(slave, TIOCSCTTY, 0);
    /* a descriptor the caller owns stays the caller's. The pty
         * keeps being the child's controlling terminal either way; only the
         * named stream is left as the executor set it. */
        if (!ar_stdin_own) dup2(slave, 0);
        if (ar_out_fd < 0) dup2(slave, 1);
        if (!ar_stderr_own) dup2(slave, 2);
        close(master); close(slave);
        execvp(argv[1], &argv[1]);
        fprintf(stderr, "شكل: %s: %s\n", argv[1], strerror(errno));
        _exit(127);
    }
    child_pid = pid;
    close(slave);

    outbuf = malloc(65536);
    if (!outbuf) { restore_stdin(); return 1; }
    outcap = 65536;
    last_data = now_ms();

    while (!child_done) {
        fd_set rfds;
        struct timeval tv = { 0, 200000 };
        int nfds = master + 1;
        FD_ZERO(&rfds);
        FD_SET(master, &rfds);
        /* ARSH_STDIN=own: the child's stdin is the caller's pipe or file and
         * must NOT be read here - reading it would consume the child's input. */
        if (!stdin_eof && !ar_stdin_own) FD_SET(0, &rfds);
        if (got_winch) { got_winch = 0; apply_winsize(master); }
        if (select(nfds, &rfds, NULL, NULL, &tv) < 0) {
            if (errno == EINTR) continue;
            break;
        }
        if (got_term) { child_done = 1; break; }
        if (!stdin_eof && FD_ISSET(0, &rfds)) {
            ssize_t r = read(0, buf, sizeof(buf));
            if (r > 0) {
                size_t done = 0;
                while (done < (size_t)r) {
                    ssize_t w = write(master, buf + done, (size_t)r - done);
                    if (w <= 0) break;
                    done += (size_t)w;
                }
            } else if (r == 0) {
                /* A piped stdin is finished: deliver EOF the way a terminal
                 * does, by sending the EOF character so the child's own line
                 * discipline ends its read (a real terminal cannot close its
                 * input half either). */
                unsigned char eofch = 0x04;
                (void)!write(master, &eofch, 1);
                stdin_eof = 1;
            }
        }
        if (FD_ISSET(master, &rfds)) {
            ssize_t r = read(master, buf, sizeof(buf));
            if (r > 0) {
                last_data = now_ms();
                if (consume_stream(buf, (size_t)r)) child_done = 1;
            } else if (r == 0) {
                child_done = 1;
            }
        }
        if (waitpid(pid, &status, WNOHANG) == pid) {
            /* drain the rest of the pty (bounded), then the tail is
             * processed after the loop */
            long deadline = now_ms() + 1000;
            while (now_ms() < deadline) {
                fd_set rf;
                struct timeval tv2 = { 0, 50000 };
                ssize_t r;
                FD_ZERO(&rf); FD_SET(master, &rf);
                if (select(master + 1, &rf, NULL, NULL, &tv2) <= 0 ||
                    !FD_ISSET(master, &rf)) break;
                r = read(master, buf, sizeof(buf));
                if (r <= 0) break;
                if (consume_stream(buf, (size_t)r)) break;
            }
            child_done = 1;
        }
        /* A partial line is emitted once the producer has been quiet for a
         * while — a prompt, or an echo mid-line.  Fragments are shaped on
         * their own, exactly as the final tail is. */
        if (!child_done && buflen && now_ms() - last_data >= 250) {
            if (emit_chunk(linebuf, buflen, 0)) child_done = 1;
            buflen = 0;
            last_data = now_ms();
        }
    }
    if (buflen) emit_chunk(linebuf, buflen, 0);
    flush_out();
    restore_stdin();
    if (WIFEXITED(status)) return WEXITSTATUS(status);
    if (WIFSIGNALED(status)) return 128 + WTERMSIG(status);
    return status;
}
