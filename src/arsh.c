/* tools/arsh.c — run an unmodified program on a pseudo-terminal and shape its
 * Arabic output for the kernel console (option C of
 * LAYER1-BRIEF.md).
 *
 * The kernel console paints one codepoint per cell, strictly left to right,
 * with no shaping and no bidi, and it drops combining marks.  This wrapper
 * runs COMMAND with stdin/stdout/stderr on a pty, reads the output, and per
 * line: shapes each run of Arabic, reorders the runs for RTL visual order,
 * and writes the result to its own stdout (the real console).  Nothing that
 * is not Arabic is touched byte-for-byte.
 *
 * No second shaping engine exists here.  The joining tables are
 * tools/ar_type_tables.h — GENERATED from Sakhr's four-form ROM JSON, the same tables
 * out/ar-type is built from — and the mark cells are tools/arsh_marks.h,
 * generated by tools/gen_arsh_tables.py by reading ar_type.c's own
 * dedicated_mark_cells and shadda_combo_codepoint definitions.
 *
 * The rules, stated exactly:
 *
 *  - A line is split on '\n'.  A line that decodes as UTF-8 and contains
 *    Arabic is reordered; every other line passes through byte-for-byte
 *    (this is why escape sequences and box drawing survive unchanged).
 *  - A line containing Presentation Forms-B (U+FE70-U+FEFC) was shaped by
 *    its producer already and is passed through whole: the forms are never
 *    shaped again and their intentional visual layout is never reordered.
 *  - Placement (D1): the line's base direction comes from the first strong
 *    codepoint after an optional producer prefix (a token of
 *    [A-Za-z0-9._/+-] followed by ": "): an Arabic letter -> RTL, an ASCII
 *    letter -> LTR, neither -> RTL.  The line is then cut into units left to
 *    right: an ARABIC chunk (Arabic plus the spaces between Arabic words),
 *    a letter island (a maximal non-Arabic stretch containing an ASCII
 *    letter, emitted whole with its internal spaces — a path is this case),
 *    and the remaining plain segments cut by class exactly as before (so a
 *    digit run, decimal, negative or thousands-separated, keeps its order,
 *    and `المجموع = 42` still renders `42 = <المجموع>`).  The unit sequence
 *    is reversed only when the base is RTL; Arabic chunks are shaped and
 *    their cells reversed either way.  A Latin run — its spaces included —
 *    is one unbreakable island, never cut into scrambled fragments, and a
 *    path is an unbroken island (bytes in order, digits in order, an Arabic
 *    component shaped RTL in place).
 *  - Marks: combining marks become the font's U+E0xx private cells, the
 *    terminal/connector choice made by the same "does the preceding letter
 *    join forward" rule ar_type.c's mark_after_forward_join uses; a shadda
 *    immediately followed by a vowel collapses into the one stacked cell
 * the stacked-cell rule, exactly as the shaper draws it.
 *  - Column layout: a shaped letter is one cell, the same as before, so
 *    Arabic columns keep their width — except a lam-alef ligature, which
 *    collapses two letters into ONE cell, and marks, which each ADD one
 *    cell where the bare kernel would have dropped them (zero cells).
 *  - Messages (D2, Route B): the wrapper's own closed table (below) is the
 *    FLOOR, not the headline.  Arabic at the source — the locale plus the
 *    packages' own catalogues (A1) and a bash catalogue we author (A3) —
 *    answers first; this table covers only what reaches us English anyway.
 *    English keys are matched EXACTLY and only when the line ends in
 *    ": <MSG>"; an unmatched line passes through byte-for-byte, never
 *    swallowed.  ARSH_MESSAGES=off disables Route B.
 *
 * Line-oriented, as the brief states: full-screen programs break, and a
 * partial line is emitted only after a quiet interval, so a producer that
 * pauses mid-line gets its Arabic shaped per fragment.  When arsh's own
 * stdout is a tty with OPOST and ONLCR, the trailing CR of each child line
 * is dropped and the tty re-adds it, so the child's CRLF is never doubled.
 * With OPOST off the tty re-adds nothing, so the CR is kept (finding 6).
 *
 * Console name: the binary is installed as شكل (shin-kaf-lam, all plain keys
 * on the Arabic-first keymap).  Build: gcc -O2 -static -o out/arsh tools/arsh.c
 */
