/* layer1/hijri.c — the Hijri date tool for the Arabic-first console.
 *
 * Prints the day's date in both calendars: the Hijri date with Arabic month
 * names, and the Gregorian date beside it, in LOGICAL (right-to-left reading)
 * order with base Arabic letters — the standard way a Unix program prints
 * Arabic.  On this kernel console, run it through the pty wrapper so the
 * Arabic reaches the screen joined and in visual order:
 *
 *     شكل hijri            (or: شكل تاريخ — the same binary under an Arabic name)
 *
 * WHICH CALENDAR THIS IS — stated exactly:
 *
 *   UMM AL-QURA, the official civil calendar of Saudi Arabia.  Its months
 *   are not a closed formula; they follow the kingdom's published table.
 *   This binary embeds that table (layer1/umalqurra.h, generated by
 *   layer1/mkumalqurra.py): month starts as Rata Die numbers, copied
 *   verbatim from the umalqurra Python package v0.2 (Khalid Al-Hussayen,
 *   PyPI), whose source states the data are R.H. van Gent's published
 *   islamcalendar_dat.js table for "The Umm al-Qura Calendar of Saudi
 *   Arabia" (http://www.staff.science.uu.nl/~gent0113/islam/ummalqura.htm).
 *   Table span: 1 Muharram 1356 AH (1937-03-14) .. 1 Muharram 1501 AH.
 *
 *   NOT the tabular (arithmetic) Islamic calendar: that pure formula (30-year
 *   leap cycle) differs from the official Saudi calendar — measured on
 *   layer1/mkumalqurra.py over AH 1420..1448: month starts differ by -2..+1
 *   days (e.g. 2026-09-26: Umm al-Qura 15 Rabi II 1448, tabular says 13).
 *
 * Locale: the output is plain UTF-8 bytes (never wide I/O), so it is
 * identical under LC_ALL=C and under any UTF-8 locale.  Digits are ASCII:
 * the console font carries no Arabic-Indic digit glyphs (U+0660-U+0669 are
 * not in out/console-16x32.psfu), so Arabic-Indic digits would paint as
 * inverse '?' on the console.  Flagged to the owner as his call.
 *
 * Build:  gcc -O2 -static -o out/hijri layer1/hijri.c
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>

#include "umalqurra.h"

/* Arabic month names, in the project's own spelling (ربيع الآخر etc.). */
static const char *const MONTH_NAMES[12] = {
    "محرم",                 /* 1 */
    "صفر",                  /* 2 */
    "ربيع الأول",           /* 3 */
    "ربيع الآخر",           /* 4 */
    "جمادى الأولى",         /* 5 */
    "جمادى الآخرة",         /* 6 */
    "رجب",                  /* 7 */
    "شعبان",                /* 8 */
    "رمضان",                /* 9 */
    "شوال",                 /* 10 */
    "ذو القعدة",            /* 11 */
    "ذو الحجة",             /* 12 */
};

/* Rata Die of a Gregorian date (RD 1 = 1 Jan 1 CE).  Reingold & Dershowitz,
 * Calendrical Calculations — the same fixed-date function mkumalqurra.py
 * verified against the published pairs. */
static int rd_of(int y, int m, int d)
{
    int leap = (y % 4 == 0 && (y % 100 != 0 || y % 400 == 0));
    return 365 * (y - 1) + (y - 1) / 4 - (y - 1) / 100 + (y - 1) / 400
           + (367 * m - 362) / 12
           + (m <= 2 ? 0 : (leap ? -1 : -2))
           + d;
}

static int days_in_month(int y, int m)
{
    static const int len[12] = {31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31};
    if (m == 2 && (y % 4 == 0 && (y % 100 != 0 || y % 400 == 0))) return 29;
    return len[m - 1];
}

/* Binary search: index of the last month start <= r, or -1 below the table. */
static int month_index(int r)
{
    int lo = 0, hi = UQ_MONTH_COUNT - 1;
    if (r < uq_month_start_rd[0]) return -1;
    while (lo < hi) {
        int mid = (lo + hi + 1) / 2;
        if (uq_month_start_rd[mid] <= r) lo = mid;
        else hi = mid - 1;
    }
    return lo;
}

/* Fill *y, *m, *d with the Umm al-Qura date of Rata Die r.  Returns 0, or
 * -1 when r is outside the published table's span (before the first month,
 * or past the end of the last month). */
static int uq_of_rd(int r, int *y, int *m, int *d)
{
    int i = month_index(r);
    int iln, day;
    if (i < 0) return -1;
    day = r - uq_month_start_rd[i] + 1;
    if (day > 30) return -1;   /* months are 29/30 days: past the last end */
    iln = UQ_FIRST_YEAR * 12 + i;
    *y = iln / 12;
    *m = iln % 12 + 1;
    *d = day;
    return 0;
}

static void usage(void)
{
    printf("usage: hijri [YYYY-MM-DD] | hijri --plain [YYYY-MM-DD] | hijri --help\n"
           "\n"
           "Prints the date in the UMM AL-QURA calendar (the official civil\n"
           "calendar of Saudi Arabia) with Arabic month names, and the\n"
           "Gregorian date beside it.  No argument = today, in the guest's\n"
           "timezone (/etc/localtime).\n"
           "\n"
           "Calendar rule, stated exactly: the month starts are the published\n"
           "Umm al-Qura table (R.H. van Gent, 'The Umm al-Qura Calendar of\n"
           "Saudi Arabia', islamcalendar_dat.js, via the umalqurra Python\n"
           "package v0.2), spanning 1 Muharram 1356 AH (1937-03-14) to\n"
           "1 Muharram 1501 AH.  This is NOT the tabular (arithmetic) Islamic\n"
           "calendar, which differs from the official Saudi calendar by up to\n"
           "2 days (measured -2..+1 over AH 1420..1448; e.g. 2026-09-26 is\n"
           "15 Rabi II 1448 here, 13 in the tabular calendar).\n"
           "\n"
           "On this console, run it through the pty wrapper so the Arabic is\n"
           "joined and in visual order:  شكل hijri   (the same binary is also\n"
           "installed as تاريخ, typable with plain keys).  Digits are ASCII\n"
           "because the console font has no Arabic-Indic digit glyphs.\n");
}

int main(int argc, char **argv)
{
    int y, m, d, hy, hm, hd, plain = 0, have_arg = 0, rd;
    time_t now;
    struct tm tm;

    if (argc > 1 && !strcmp(argv[1], "--help")) { usage(); return 0; }
    if (argc > 1 && !strcmp(argv[1], "--plain")) { plain = 1; --argc; ++argv; }
    if (argc > 2) { usage(); return 2; }

    if (argc == 2) {
        if (sscanf(argv[1], "%d-%d-%d", &y, &m, &d) != 3 ||
            m < 1 || m > 12 || d < 1 || d > days_in_month(y, m)) {
            fprintf(stderr, "hijri: bad date '%s' (want a real YYYY-MM-DD)\n",
                    argv[1]);
            return 2;
        }
        have_arg = 1;
    } else {
        now = time(NULL);
        if (!localtime_r(&now, &tm)) {
            fprintf(stderr, "hijri: localtime_r failed\n");
            return 1;
        }
        y = tm.tm_year + 1900;
        m = tm.tm_mon + 1;
        d = tm.tm_mday;
    }

    rd = rd_of(y, m, d);
    if (uq_of_rd(rd, &hy, &hm, &hd)) {
        fprintf(stderr, "hijri: %04d-%02d-%02d is outside the Umm al-Qura "
                        "table's span (1356-1500 AH)\n", y, m, d);
        return 1;
    }

    if (plain) {
        printf("%04d-%02d-%02d %04d-%02d-%02d\n", hy, hm, hd, y, m, d);
        return 0;
    }

    /* The Arabic line, in LOGICAL order (right-to-left reading): day, month
     * name, year, هـ, الموافق, Gregorian date + م.  The wrapper reverses the
     * runs for the console; the digit runs keep their order. */
    printf("%s: %d %s %d هـ الموافق %02d/%02d/%04dم\n",
           have_arg ? "التاريخ" : "اليوم",
           hd, MONTH_NAMES[hm - 1], hy, d, m, y);
    return 0;
}
