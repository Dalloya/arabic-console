#!/usr/bin/env python3
"""layer1/mkshaped.py — generate layer1/shaped.h.

Emits C string literals for the demo's Arabic output, in the VISUAL (left to
right) order the kernel console paints, using the SAME engine that shaped the
font: tools/shape.py (which imports tools/join.py, the table that was audited
against Unicode ArabicShaping.txt by tools/join_audit.py).

Run:  python3 layer1/mkshaped.py
Then: gcc -o hisab layer1/hisab.c
"""
import sys
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
from shape import shape          # noqa: E402  (engine: logical -> visual forms)

# One entry per literal the demo needs.  LOGICAL Arabic on the left.
LITERALS = {
    "SHAPED_LABEL": "المجموع",
    "SHAPED_WORD": "سلام",
}

OUT = ROOT / "layer1" / "shaped.h"


def c_escape(cps):
    return "".join(f"\\u{cp:04X}" for cp in cps)


def main():
    lines = [
        "/* GENERATED by layer1/mkshaped.py - do not edit.",
        " * Arabic in the console's visual order: words and the joined glyphs",
        " * within each word are reversed, because the kernel console paints",
        " * cells strictly left to right.  Presentation Forms-B, not base",
        " * letters: the font maps the forms, so the screen shows joined text.  */",
        "#ifndef SHAPED_H",
        "#define SHAPED_H",
    ]
    for name, logical in LITERALS.items():
        cps = shape(logical)
        lines.append("")
        lines.append(f"/* logical: {logical}")
        lines.append(" * cells  : " + " ".join(f"U+{c:04X}" for c in cps) + " */")
        lines.append(f'#define {name} "{c_escape(cps)}"')
    lines.append("")
    lines.append("#endif")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
